"""Turn an Analysis into something people (terminal, PR comment) or machines (JSON) can use."""

from __future__ import annotations

import json
import re

from rich.console import Console, Group
from rich.markup import escape
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from . import __version__
from .impact import Analysis
from .models import Change, ChangeImpact, ConsumerImpact, Impact, Severity

_IMPACT_ORDER = {Impact.WILL_BREAK: 0, Impact.MAY_BREAK: 1, Impact.UNAFFECTED: 2}
_SEVERITY_ORDER = {Severity.BREAKING: 0, Severity.WARNING: 1, Severity.SAFE: 2}


def _sorted_impacts(analysis: Analysis) -> list[ChangeImpact]:
    """Worst first: changes that break someone, then may break, then the rest."""
    return sorted(
        analysis.impacts,
        key=lambda ci: (_IMPACT_ORDER[ci.worst], _SEVERITY_ORDER[ci.change.severity]),
    )


def _sorted_sites(ci: ChangeImpact) -> list[ConsumerImpact]:
    return sorted(ci.impacts, key=lambda i: (_IMPACT_ORDER[i.impact], i.site.consumer, i.site.line))


def _plural(n: int, word: str) -> str:
    return f"{n} {word}" if n == 1 else f"{n} {word}s"


# --- Markdown (pull-request comment) ---------------------------------------

_MD_IMPACT = {
    Impact.WILL_BREAK: "🔴 will break",
    Impact.MAY_BREAK: "🟡 may break",
    Impact.UNAFFECTED: "🟢 unaffected",
}
_MD_SEVERITY = {Severity.BREAKING: "❌", Severity.WARNING: "⚠️", Severity.SAFE: "✅"}


def to_markdown(analysis: Analysis) -> str:
    will = analysis.consumers_with(Impact.WILL_BREAK)
    may = analysis.consumers_with(Impact.MAY_BREAK)
    out = ["## 💥 BlastRadius report", ""]

    if will:
        out.append(
            f"**{_plural(len(will), 'consumer')} will break:** " + ", ".join(f"`{c}`" for c in will)
        )
    elif may:
        out.append("**No consumer is certain to break**, but some need a look.")
    else:
        out.append("**✅ No consumer is affected by this change.**")
    out += [
        "",
        (
            f"{_plural(len(analysis.breaking), 'breaking change')} in the spec · "
            f"{_plural(len(will), 'consumer')} will break · {len(may)} more may break · "
            f"{_plural(len(analysis.sites), 'call site')} scanned in "
            f"{_plural(len(analysis.consumers), 'consumer')}"
        ),
        "",
    ]

    quiet = []
    for ci in _sorted_impacts(analysis):
        if not ci.affected:
            quiet.append(ci.change)
            continue
        c = ci.change
        out += [
            f"### {_MD_SEVERITY[c.severity]} `{c.endpoint}`: {c.message}{_md_uncertain(c)}",
            "",
            "| Consumer | Location | Impact | Why |",
            "|---|---|---|---|",
        ]
        for i in _sorted_sites(ci):
            out.append(
                f"| `{i.site.consumer}` | `{i.site.location}` | "
                f"{_MD_IMPACT[i.impact]} | {i.reason} |"
            )
        out.append("")

    if quiet:
        out += [
            "<details>",
            (
                f"<summary>{_plural(len(quiet), 'more change')} with no affected consumers "
                "(safe to ship as far as we can see)</summary>"
            ),
            "",
        ]
        out += [
            f"- {_MD_SEVERITY[c.severity]} `{c.endpoint}`: {c.message}{_md_uncertain(c)}"
            for c in quiet
        ]
        out += ["", "</details>", ""]

    if analysis.unmatched:
        out += [
            "<details>",
            (
                f"<summary>{_plural(len(analysis.unmatched), 'call')} to endpoints not in this "
                "spec (other APIs, or undocumented endpoints)</summary>"
            ),
            "",
        ]
        out += [
            f"- `{s.consumer}` `{s.location}`: `{s.method} {s.url}`" for s in analysis.unmatched
        ]
        out += ["", "</details>", ""]

    safe = sum(1 for c in analysis.changes if c.severity is Severity.SAFE)
    if safe:
        out.append(f"_{_plural(safe, 'non-breaking change')} not shown._")
    out.append(f"<sub>Generated by BlastRadius {__version__}</sub>")
    return "\n".join(out) + "\n"


def _md_uncertain(c: Change) -> str:
    return "" if c.certain else " _(uncertain: inside a oneOf/anyOf)_"


# --- JSON (CI, dashboards) -------------------------------------------------


def change_to_dict(c: Change) -> dict:
    return {
        "kind": c.kind.value,
        "severity": c.severity.value,
        "method": c.method,
        "path": c.path,
        "field": c.field,
        "message": c.message,
        "before": c.before,
        "after": c.after,
        # False for changes inside a oneOf/anyOf branch: whether a consumer gets (or
        # sends) that branch can't be known, so these are never more than "may break".
        "certain": c.certain,
    }


def to_dict(analysis: Analysis) -> dict:
    """The full analysis as plain data: used for JSON output and by the web API."""
    return {
        "version": __version__,
        "summary": {
            "breaking_changes": len(analysis.breaking),
            "consumers": analysis.consumers,
            "will_break": analysis.consumers_with(Impact.WILL_BREAK),
            "may_break": analysis.consumers_with(Impact.MAY_BREAK),
            "call_sites": len(analysis.sites),
            "unmatched_call_sites": len(analysis.unmatched),
        },
        "changes": [
            {
                **change_to_dict(ci.change),
                "worst_impact": ci.worst.value,
                "impacts": [
                    {
                        "consumer": i.site.consumer,
                        "file": i.site.file,
                        "line": i.site.line,
                        "impact": i.impact.value,
                        "reason": i.reason,
                        "code": i.site.snippet,
                    }
                    for i in _sorted_sites(ci)
                ],
            }
            for ci in _sorted_impacts(analysis)
        ],
        "safe_changes": [
            change_to_dict(c) for c in analysis.changes if c.severity is Severity.SAFE
        ],
        "unmatched": [
            {
                "consumer": s.consumer,
                "file": s.file,
                "line": s.line,
                "method": s.method,
                "url": s.url,
            }
            for s in analysis.unmatched
        ],
    }


def to_json(analysis: Analysis) -> str:
    return json.dumps(to_dict(analysis), indent=2) + "\n"


# --- Terminal --------------------------------------------------------------

_TERM_IMPACT = {
    Impact.WILL_BREAK: "[bold red]● will break[/]",
    Impact.MAY_BREAK: "[yellow]● may break[/]",
    Impact.UNAFFECTED: "[green]● unaffected[/]",
}
_TERM_SEVERITY = {
    Severity.BREAKING: "[bold red]BREAKING[/]",
    Severity.WARNING: "[yellow]WARNING[/]",
    Severity.SAFE: "[green]SAFE[/]",
}


def _code(text: str) -> str:
    """`field` -> bold cyan, with everything else escaped for Rich markup."""
    return re.sub(r"`([^`]*)`", r"[bold cyan]\1[/]", escape(text))


def print_analysis(analysis: Analysis, console: Console) -> None:
    will = analysis.consumers_with(Impact.WILL_BREAK)
    may = analysis.consumers_with(Impact.MAY_BREAK)

    if will:
        headline = Text.from_markup(
            f"[bold red]💥 {_plural(len(will), 'consumer')} will break:[/] " + ", ".join(will)
        )
    elif may:
        headline = Text.from_markup(
            "[bold yellow]No consumer is certain to break, but some need a look.[/]"
        )
    else:
        headline = Text.from_markup("[bold green]✅ No consumer is affected by this change.[/]")
    stats = Text(
        f"{_plural(len(analysis.breaking), 'breaking change')} in the spec · "
        f"{len(will)} will break · {len(may)} more may break · "
        f"{_plural(len(analysis.sites), 'call site')} in "
        f"{_plural(len(analysis.consumers), 'consumer')}",
        style="dim",
    )
    console.print(Panel(Group(headline, stats), title="BlastRadius", title_align="left"))

    quiet = 0
    for ci in _sorted_impacts(analysis):
        if not ci.affected:
            quiet += 1
            continue
        c = ci.change
        console.print(f"\n{_TERM_SEVERITY[c.severity]} [bold]{escape(c.endpoint)}[/]")
        console.print(f"  {_code(c.message)}")
        for i in _sorted_sites(ci):
            # Two lines per consumer, so it stays readable in a narrow terminal.
            console.print(
                f"    {_TERM_IMPACT[i.impact]}  [bold]{escape(i.site.consumer)}[/]  "
                f"[dim]{escape(i.site.location)}[/]"
            )
            console.print(
                f"      {_code(i.reason)}", style="dim" if i.impact is Impact.UNAFFECTED else None
            )

    if quiet:
        console.print(
            f"\n[green]✓[/] {_plural(quiet, 'more breaking/warning change')} "
            "with no affected consumers (use --format markdown or json to list them)"
        )
    if analysis.unmatched:
        n = len(analysis.unmatched)
        console.print(
            f"[dim]ℹ {_plural(n, 'call')} to endpoints not in this spec "
            f"{'was' if n == 1 else 'were'} ignored[/]"
        )


def print_changes(changes: list[Change], console: Console, show_safe: bool = False) -> None:
    shown = [c for c in changes if show_safe or c.severity is not Severity.SAFE]
    shown.sort(key=lambda c: _SEVERITY_ORDER[c.severity])
    if not shown:
        console.print("[green]No breaking changes or warnings.[/]")
    else:
        table = Table(show_header=True, header_style="bold", box=None, padding=(0, 2, 0, 0))
        table.add_column("Severity")
        table.add_column("Endpoint")
        table.add_column("Change")
        for c in shown:
            table.add_row(_TERM_SEVERITY[c.severity], escape(c.endpoint), _code(c.message))
        console.print(table)

    hidden = len(changes) - len(shown)
    if hidden:
        console.print(f"[dim]{_plural(hidden, 'safe change')} hidden (use --all to show)[/]")
